"""Regenerates models_gen.py from schema.json."""
import json
from pathlib import Path

HEADER = "# GENERATED by gen.py from schema.json. Edits here are overwritten.\n"


def render(schema):
    out = [HEADER, "from dataclasses import dataclass\n"]
    for name, fields in schema.items():
        out.append(f"\n\n@dataclass\nclass {name}:\n")
        out.extend(f"    {field}: str = \"\"\n" for field in fields)
    return "".join(out)


if __name__ == "__main__":
    here = Path(__file__).parent
    schema = json.loads((here / "schema.json").read_text())
    (here / "models_gen.py").write_text(render(schema))
